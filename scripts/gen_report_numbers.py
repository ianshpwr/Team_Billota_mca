#!/usr/bin/env python3
"""Write docs/report_numbers.tex: LaTeX macros holding every number quoted in the report,
extracted from the saved result files so the report cannot drift from the evidence.
Usage (repo root): python3 -I scripts/gen_report_numbers.py"""
import csv, glob, re

def rd(p): return open(p).read()
n = {}
d4 = rd("build/d_L4.log")
m = re.search(r"TESTS=(\d+) TESTS_FAILED=(\d+) CHECKS_PASS=(\d+) CHECKS_FAIL=(\d+)", d4)
n["DirTests"], n["DirTestsFailed"], n["DirChecks"], n["DirChecksFailed"] = m.groups()
n["FixedLats"] = str(len(glob.glob("build/d_L*.log")))
n["VarLats"] = str(len(glob.glob("build/v_L*.log")))
rm = rd("results/reference_model_results.txt")
m = re.search(r"TOTAL runs=(\d+)\s+passed=(\d+)\s+failed=(\d+)\s+\(fixed-latency DUT transactions compared against the model: (\d+)\)", rm)
n["RefRuns"], n["RefPassed"], n["RefFailed"], n["RefTxns"] = m.groups()
mut = [l for l in open("results/phase2_mutation_results.txt") if re.match(r"M\d\d", l)]
pat = r"(detected|SURVIVED)\s+(detected|SURVIVED)"
n["Mutants"] = str(len(mut))
n["MutDetPhaseOne"] = str(sum(re.search(pat, l).group(1) == "detected" for l in mut))
n["MutDetPhaseTwo"] = str(sum(re.search(pat, l).group(2) == "detected" for l in mut))
p1 = rd("results/phase1_test_results.txt")
n["PhaseOneChecks"] = re.search(r"PASS=(\d+) FAIL=0", p1).group(1)
cov = {}
for ln in d4.splitlines():
    m = re.match(r"COVERAGE,(\w+),(\d+),(\d*)", ln)
    if m: cov[m.group(1)] = int(m.group(2))
n["CovStates"] = str(cov["states_visited"]); n["CovTrans"] = str(cov["legal_transitions_visited"])
n["CovReadHit"], n["CovReadMiss"] = str(cov["read_hit"]), str(cov["read_miss"])
n["CovWriteHit"], n["CovWriteMiss"] = str(cov["write_hit"]), str(cov["write_miss"])
n["CovConflict"], n["CovCold"] = str(cov["conflict_misses_valid_line"]), str(cov["cold_misses_invalid_line"])
ic = lambda f: (re.search(r"(\d+)\s+SB_DFFESR", rd(f)).group(1), re.search(r"(\d+)\s+SB_LUT4", rd(f)).group(1))
c_ff, c_lut = ic("build/ys_ice40_cache_controller.log"); m_ff, m_lut = ic("build/ys_ice40_cache_memory.log")
n["IceFFCtl"], n["IceLutCtl"], n["IceFFMem"], n["IceLutMem"] = c_ff, c_lut, m_ff, m_lut
n["IceFFTot"] = str(int(c_ff) + int(m_ff)); n["IceLutTot"] = str(int(c_lut) + int(m_lut))
rows = list(csv.DictReader(open("results/performance_metrics.csv")))
n["PerfRows"] = str(len(rows))
def mean(x): return sum(x) / len(x)
def wl(w, L, k): return mean([float(r[k]) for r in rows if r["workload"] == w and int(r["mem_latency_L"]) == L])
for w, key in [("uniform", "Uni"), ("hotset", "Hot"), ("conflict", "Con"), ("sequential", "Seq"), ("write_heavy", "Wri"), ("mixed_reset", "Mix"), ("corners", "Cor"), ("tagbits", "Tag")]:
    n["HR" + key] = "%.3f" % wl(w, 4, "hit_ratio")
    n["Lat" + key] = "%.2f" % wl(w, 4, "avg_latency_cycles")
    n["AmatRead" + key] = "%.2f" % mean([float(r["amat_read_formula"]) for r in rows if r["workload"] == w and int(r["mem_latency_L"]) == 4 and r["amat_read_formula"]])
n["LatWriHeavySixteen"] = "%.2f" % wl("write_heavy", 16, "avg_latency_cycles")
n["LatHotSixteen"] = "%.2f" % wl("hotset", 16, "avg_latency_cycles")
with open("docs/report_numbers.tex", "w") as f:
    f.write("% generated by scripts/gen_report_numbers.py - do not edit\n")
    for k, v in n.items():
        f.write("\\newcommand{\\n%s}{%s}\n" % (k, v))
print("wrote docs/report_numbers.tex with %d macros" % len(n))
