#!/usr/bin/env python3
"""Generate Phase 2 reports from the saved regression logs (nothing typed by hand):
   TEST_RESULTS.md, results/complete_test_results.txt, results/coverage_summary.md,
   results/performance_summary.md.     Usage (repo root): python3 -I scripts/gen_phase2_reports.py
Run after scripts/phase2_regression.sh (needs build/d_L*.log, build/v_L*.log)."""
import csv, glob, os, re, subprocess, collections, datetime

R = "results"
def sh(cmd):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout.strip()

fixed_logs = sorted(glob.glob("build/d_L*.log"), key=lambda p: int(re.search(r"d_L(\d+)", p).group(1)))
var_logs = sorted(glob.glob("build/v_L*.log"), key=lambda p: int(re.search(r"v_L(\d+)", p).group(1)))
main_log = "build/d_L4.log"
assert os.path.exists(main_log), "run scripts/phase2_regression.sh first"
text = open(main_log).read().splitlines()

# ---------------------------------------------------------------- parse main log
tests = collections.OrderedDict()
cur = None
for ln in text:
    m = re.match(r"\[TEST\] (\S+) : (.*)", ln)
    if m: cur = m.group(1); tests[cur] = dict(desc=m.group(2), init="", stim="", checks=0, fail=0, res="?"); continue
    m = re.match(r"\s+init: (.*)", ln)
    if m and cur: tests[cur]["init"] = m.group(1); continue
    m = re.match(r"\s+stim: (.*)", ln)
    if m and cur: tests[cur]["stim"] = m.group(1); continue
    m = re.match(r"\[TEST-RESULT\] (\S+) (PASS|FAIL) \((\d+)", ln)
    if m: tests[m.group(1)]["res"] = m.group(2); tests[m.group(1)]["checks"] = int(m.group(3))

checks = collections.OrderedDict()
pat = re.compile(r"^\s+\[(PASS|FAIL)\] (\S+) (.*?) \| (?:expected=(\S+) actual=(\S+)|(\d+) sub-checks, (\d+) mismatches)")
for ln in text:
    m = pat.match(ln)
    if not m: continue
    res, cid, desc, e, a, nsub, nbad = m.groups()
    c = checks.setdefault(cid, dict(desc=desc.strip(), n=0, fail=0, exp=e, act=a, sub=0))
    c["n"] += 1
    if res == "FAIL": c["fail"] += 1
    if nsub: c["exp"] = "0 mismatches"; c["act"] = "%s sub-checks, %s mismatches" % (nsub, nbad); c["sub"] += int(nsub)

def per_log_status(logs):
    st = collections.defaultdict(list)
    for p in logs:
        cur = None
        for ln in open(p):
            m = re.match(r"\[TEST-RESULT\] (\S+) (PASS|FAIL)", ln)
            if m: st[m.group(1)].append(m.group(2))
    return st
st_fixed, st_var = per_log_status(fixed_logs), per_log_status(var_logs)

# --------------------------------------------------------------- TEST_RESULTS.md

out = []
out.append("# TEST_RESULTS.md - Consolidated Test Register\n")
out.append("*Generated by `scripts/gen_phase2_reports.py` (and `scripts/gen_test_register.py` for Phase 1) from the saved logs in `results/` and `build/`. Do not edit by hand.*\n")
out.append("Environment: %s; %s; Python %s\n" % (sh("iverilog -V 2>&1 | head -1"), sh("yosys -V 2>&1 | head -1 | cut -c1-12"), sh("python3 --version | cut -d' ' -f2")))
out.append("## Phase 2 - summary\n")
sweep = open(f"{R}/phase2_latency_sweep.txt").read()
n_fix = len(fixed_logs); n_var = len(var_logs)
tot_tests = len(tests); tot_pass = sum(1 for t in tests.values() if t["res"] == "PASS")
out.append("| Item | Result | Evidence |")
out.append("|---|---|---|")
out.append("| Directed + edge-case tests (D-00..D-30, E-01..E-11, L-01, C-01) at L=4 with exhaustive 64 KiB sweep | %d of %d tests PASS | `results/complete_test_results.txt` |" % (tot_pass, tot_tests))
all_fixed = all(all(r == "PASS" for r in v) and len(v) == n_fix for v in st_fixed.values())
out.append("| Same tests at %d fixed memory latencies (L = 0..16, 32, 64, 100, 255, 1000) | %s | `results/phase2_latency_sweep.txt` |" % (n_fix, "all PASS at every latency" if all_fixed else "FAILURES - see file"))
all_var = all(all(r == "PASS" for r in v) and len(v) == n_var for v in st_var.values())
out.append("| Same tests with pseudo-random per-transaction memory latency (max 2, 3, 8, 16, 40) | %s | `results/phase2_latency_sweep.txt` |" % ("all PASS" if all_var else "FAILURES"))
rm = open(f"{R}/reference_model_results.txt").read()
mm = re.search(r"TOTAL runs=(\d+)\s+passed=(\d+)\s+failed=(\d+)\s+\(fixed-latency DUT transactions compared against the model: (\d+)\)", rm)
out.append("| Randomized + vector regression vs independent Python model | %s runs, %s passed, %s failed; %s transactions compared | `results/reference_model_results.txt` |" % (mm.group(1), mm.group(2), mm.group(3), mm.group(4)))
mut = [l for l in open(f"{R}/phase2_mutation_results.txt") if re.match(r"M\d\d", l)]
p2_det = sum(1 for l in mut if len(l.split("  ")) and re.search(r"(detected|SURVIVED)\s+(detected|SURVIVED)", l) and re.search(r"(detected|SURVIVED)\s+(detected|SURVIVED)", l).group(2) == "detected")
p1_det = sum(1 for l in mut if re.search(r"(detected|SURVIVED)\s+(detected|SURVIVED)", l).group(1) == "detected")
out.append("| Mutation check, %d injected RTL bugs | Phase 2 directed bench detects %d/%d; Phase 1 bench detects %d/%d | `results/phase2_mutation_results.txt` |" % (len(mut), p2_det, len(mut), p1_det, len(mut)))
out.append("")
out.append("## Phase 2 - test register (L = 4, exhaustive sweep enabled)\n")
out.append("Columns: test ID, description, initial condition, stimulus, checks executed, result at L=4, and the number of the %d fixed-latency / %d variable-latency runs in which the test passed.\n" % (n_fix, n_var))
out.append("| Test ID | Description | Initial conditions | Stimulus | Checks | Result (L=4) | Pass count fixed-L runs | Pass count var-L runs |")
out.append("|---|---|---|---|---|---|---|---|")
for tid, t in tests.items():
    out.append("| %s | %s | %s | %s | %d | %s | %d/%d | %d/%d |" % (tid, t["desc"], t["init"], t["stim"], t["checks"], t["res"],
               st_fixed[tid].count("PASS"), n_fix, st_var[tid].count("PASS"), n_var))
out.append("")
out.append("## Phase 2 - per-check detail (expected vs actual, first execution at L=4)\n")
out.append("| Check ID | Description | Runs | Expected | Actual | Result |")
out.append("|---|---|---|---|---|---|")
for cid, c in checks.items():
    out.append("| %s | %s | %d | %s | %s | %s |" % (cid, c["desc"].replace("|", "/"), c["n"], c["exp"], c["act"], "PASS" if c["fail"] == 0 else "FAIL (%d)" % c["fail"]))
out.append("")
out.append("**Totals (L=4):** %d tests, %d distinct check IDs, %d check lines executed, %d failures.\n" % (tot_tests, len(checks), sum(c["n"] for c in checks.values()), sum(c["fail"] for c in checks.values())))

# Phase 1 section (kept, regenerated from the preserved Phase 1 logs)
p1log = "results/phase1_test_results.txt"
p1 = collections.OrderedDict()
pp = re.compile(r"^\[(PASS|FAIL)\] (\S+) (.*?) \| expected=(\S+) actual=(\S+)")
for ln in open(p1log):
    m = pp.match(ln)
    if m:
        res, tid, desc, e, a = m.groups()
        r = p1.setdefault(tid, dict(desc=desc, n=0, fail=0, e=e, a=a)); r["n"] += 1; r["fail"] += (res == "FAIL")
out.append("## Phase 1 - directed tests (`testbench/cache_tb.v`, L = 4) - preserved evidence\n")
out.append("| Test ID | Description | Runs | Expected | Actual | Result | Evidence |")
out.append("|---|---|---|---|---|---|---|")
for tid, r in p1.items():
    out.append("| %s | %s | %d | %s | %s | %s | `%s` |" % (tid, r["desc"], r["n"], r["e"], r["a"], "PASS" if r["fail"] == 0 else "FAIL", p1log))
out.append("")
out.append("**Phase 1 totals:** %d IDs, %d check executions, %d failures.\n" % (len(p1), sum(r["n"] for r in p1.values()), sum(r["fail"] for r in p1.values())))
p1sw = open("results/phase1_latency_sweep.txt").read()
for L, p, f in re.findall(r"SUMMARY \(MEM_LATENCY=(\d+)\): PASS=(\d+) FAIL=(\d+)", p1sw):
    out.append("* Phase 1 testbench at MEM_LATENCY=%s: PASS=%s FAIL=%s (`results/phase1_latency_sweep.txt`)" % (L, p, f))
out.append("\n## Phase 3\n\nNOT STARTED at the time this file was generated (see PHASE_STATUS.md).\n")
open("TEST_RESULTS.md", "w").write("\n".join(out))

# ------------------------------------------------------ coverage_summary.md
cov = collections.OrderedDict()
for p in fixed_logs:
    L = int(re.search(r"d_L(\d+)", p).group(1))
    cov[L] = {}
    for ln in open(p):
        m = re.match(r"COVERAGE,(\w+),(\d+),(\d*)", ln)
        if m: cov[L][m.group(1)] = (int(m.group(2)), m.group(3))
c4 = cov[4]
md = []
md.append("# Coverage Summary (Phase 2)\n")
md.append("**What this is.** *Functional* coverage counted by the testbench monitor (`testbench/tb_common.vh`) from the actual simulation: FSM states and transitions visited, cache indices/offsets exercised, hit/miss classes. **What it is not.** No RTL *line/branch/toggle* coverage tool was used or run (Icarus Verilog has none; Verilator coverage was not enabled), so **no line-coverage percentage is claimed.** All counts below are taken from the saved logs `build/d_L*.log` (regenerated by `scripts/phase2_regression.sh`).\n")
md.append("## Run at L = 4 (exhaustive 64 KiB sweep enabled)\n")
md.append("| Metric | Observed | Goal |")
md.append("|---|---|---|")
goal = {"states_visited": "10 of 10 FSM states", "legal_transitions_visited": "17 of 17 legal transitions", "illegal_transitions_visited": "0 illegal transitions",
        "index_read": "16 of 16 indices read", "index_write": "16 of 16 indices written", "offset_read": "4 of 4 offsets read", "offset_write": "4 of 4 offsets written"}
names = {"states_visited": "FSM states visited", "legal_transitions_visited": "Legal FSM transitions visited", "illegal_transitions_visited": "Illegal FSM transitions observed",
         "index_read": "Cache indices read", "index_write": "Cache indices written", "offset_read": "Byte offsets read", "offset_write": "Byte offsets written"}
for k in goal:
    v = c4[k][0]; tot = c4[k][1] or "-"
    md.append("| %s | %s%s | %s |" % (names[k], v, (" of " + tot) if k != "illegal_transitions_visited" else "", goal[k]))
for k, label in [("read_hit", "Read hits"), ("read_miss", "Read misses"), ("write_hit", "Write hits"), ("write_miss", "Write misses"),
                 ("cold_misses_invalid_line", "Misses on an INVALID line (cold)"), ("conflict_misses_valid_line", "Misses on a VALID line (conflict replacement)")]:
    md.append("| %s | %d | > 0 |" % (label, c4[k][0]))
md.append("")
md.append("## FSM transition coverage (the 17 legal transitions)\n")
md.append("`IDLE->IDLE, IDLE->COMPARE_TAG, COMPARE_TAG->{READ_HIT, READ_MISS, WRITE_HIT, WRITE_MISS}, READ_HIT->RESPONSE, READ_MISS->MEMORY_READ_WAIT, WRITE_MISS->MEMORY_READ_WAIT, MEMORY_READ_WAIT->{MEMORY_READ_WAIT, REFILL}, REFILL->{READ_HIT, WRITE_HIT}, WRITE_HIT->MEMORY_WRITE_WAIT, MEMORY_WRITE_WAIT->{MEMORY_WRITE_WAIT, RESPONSE}, RESPONSE->IDLE`. "
          "All 17 were visited at every latency except L=1, where the read-wait state lasts one cycle so the `MEMORY_READ_WAIT->MEMORY_READ_WAIT` self-loop cannot occur (16 reachable transitions, all visited).\n")
md.append("The six unused state encodings (10-15) are covered by test E-11 (forced into each code; outputs quiet; self-recovers to IDLE in one clock).\n")
md.append("## Across memory latencies\n")
md.append("| L | states | legal transitions | illegal | indices R/W | offsets R/W | read hits | read misses | write hits | write misses | conflict misses |")
md.append("|---|---|---|---|---|---|---|---|---|---|---|")
for L, c in cov.items():
    md.append("| %d | %d/10 | %d/%s | %d | %d/%d | %d/%d | %d | %d | %d | %d | %d |" % (L, c["states_visited"][0], c["legal_transitions_visited"][0], c["legal_transitions_visited"][1],
              c["illegal_transitions_visited"][0], c["index_read"][0], c["index_write"][0], c["offset_read"][0], c["offset_write"][0],
              c["read_hit"][0], c["read_miss"][0], c["write_hit"][0], c["write_miss"][0], c["conflict_misses_valid_line"][0]))
md.append("")
md.append("## Requirement-level coverage\n")
md.append("Spec-section 2.1 tests 1-30 map to IDs D-01..D-30 (D-24 is split into D-24, D-24R, D-24W, D-24A for reset in each transaction type); 2.2 edge cases map to E-01..E-11; all are in `TEST_RESULTS.md`. "
          "The independent reference-model comparison (`results/reference_model_results.txt`) adds %s randomized/vector transactions in 8 workload profiles with fixed seeds.\n" % mm.group(4))
md.append("## Not covered / limits\n")
md.append("* No RTL line/branch/toggle coverage numbers (no tool run).\n* `LATENCY` values > 65535 are outside the 16-bit counter range and untested (documented limit).\n* Per-transaction random latency is tested only through the testbench-only `tb_mem_varlat` model, not through `rtl/main_memory.v`.\n* Simultaneous multi-master or pipelined requests are not supported by the design and not tested.\n")
open(f"{R}/coverage_summary.md", "w").write("\n".join(md))

# ------------------------------------------------------ performance_summary.md
rows = list(csv.DictReader(open(f"{R}/performance_metrics.csv")))
rnd = [r for r in rows if r["workload"] in ("uniform", "hotset", "conflict", "sequential", "write_heavy", "mixed_reset", "corners", "tagbits")]
byw = collections.defaultdict(list)
for r in rnd: byw[(r["workload"], int(r["mem_latency_L"]))].append(r)
def mean(xs): return sum(xs) / len(xs)
pm = []
pm.append("# Performance Metrics Summary (Phase 2)\n")
pm.append("All numbers are computed by `verification/performance.py` from the **actual simulation logs** of the RTL (clock cycles of the simulated design). No clock frequency, FPGA or silicon timing is assumed or claimed. Raw per-run data: `results/performance_metrics.csv` (%d rows).\n" % len(rows))
pm.append("## Assumptions and definitions\n")
pm.append("* Latency = cycles from request acceptance to the response edge. Documented/measured: read hit 3, read miss 5+L, write hit 4+L, write miss 6+2L (L = main-memory latency in cycles).\n"
          "* Hit ratio = hits/requests; miss ratio = misses/requests (a write is a hit if its block is cached).\n"
          "* `AMAT_read = H + MR_read x MP` with H = 3 and MP = 2+L is the textbook formula and applies to **reads only**: every write pays the write-through memory latency (4+L even on a hit), so the single-formula AMAT underestimates mixed workloads.\n"
          "* `AMAT_class` = sum over {read hit, read miss, write hit, write miss} of fraction x documented latency. It equals the measured average latency because the formulas were verified on every transaction by the testbench monitor; it is a *consistency check*, not independent evidence.\n"
          "* Workloads are synthetic (generator profiles in `verification/randomized_tests.py`, fixed seeds 1-6, 2500 requests each); hit ratios say nothing about real programs.\n")
pm.append("## Mean over seeds 1-6, 2500 requests per run, memory latency L = 4\n")
pm.append("| Workload | Requests | Reads | Writes | Hit ratio | Miss ratio | Mem reads | Mem writes | Avg latency (cycles) | AMAT_read (cycles) | AMAT_class (cycles) |")
pm.append("|---|---|---|---|---|---|---|---|---|---|---|")
for w in ("uniform", "hotset", "conflict", "sequential", "write_heavy", "mixed_reset", "corners", "tagbits"):
    g = byw[(w, 4)]
    if not g: continue
    pm.append("| %s | %.0f | %.0f | %.0f | %.4f | %.4f | %.0f | %.0f | %.3f | %.3f | %.3f |" % (w, mean([int(x["total_requests"]) for x in g]), mean([int(x["reads"]) for x in g]), mean([int(x["writes"]) for x in g]),
        mean([float(x["hit_ratio"]) for x in g]), mean([float(x["miss_ratio"]) for x in g]), mean([int(x["mem_read_txns"]) for x in g]), mean([int(x["mem_write_txns"]) for x in g]),
        mean([float(x["avg_latency_cycles"]) for x in g]), mean([float(x["amat_read_formula"]) for x in g if x["amat_read_formula"]]), mean([float(x["amat_class_weighted"]) for x in g])))
pm.append("\n## Average latency (cycles) versus memory latency L (mean over seeds)\n")
Ls = sorted({int(r["mem_latency_L"]) for r in rnd})
pm.append("| Workload | " + " | ".join("L=%d" % L for L in Ls) + " |")
pm.append("|---|" + "---|" * len(Ls))
for w in ("uniform", "hotset", "conflict", "sequential", "write_heavy", "mixed_reset", "corners", "tagbits"):
    pm.append("| %s | " % w + " | ".join("%.2f" % mean([float(x["avg_latency_cycles"]) for x in byw[(w, L)]]) for L in Ls) + " |")
pm.append("\n## Measured vs predicted\n")
dif = max(abs(float(r["avg_latency_cycles"]) - float(r["amat_class_weighted"])) for r in rnd)
pm.append("Maximum |measured average latency - class-weighted prediction| over all %d fixed-latency runs: **%.6f cycles** (rounding only).\n" % (len(rnd), dif))
pm.append("Write-through cost: in the `write_heavy` workload the average latency at L=16 is %.2f cycles versus %.2f for `hotset` (read-dominant), because every write stalls for the memory write.\n" %
          (mean([float(x["avg_latency_cycles"]) for x in byw[("write_heavy", 16)]]), mean([float(x["avg_latency_cycles"]) for x in byw[("hotset", 16)]])))
open(f"{R}/performance_summary.md", "w").write("\n".join(pm))

# ------------------------------------------------------ complete_test_results.txt
ver = sh("iverilog -V 2>&1 | head -1")
cm = []
cm.append("# complete_test_results.txt - Phase 2 consolidated simulation evidence")
cm.append("# generated %s by scripts/gen_phase2_reports.py from build/*.log, results/*" % datetime.datetime.now().strftime("%Y-%m-%d %H:%M"))
cm.append("# tool: %s" % ver)
cm.append("# command (per latency L): iverilog -g2001 -Wall -I testbench -s cache_tb_directed -P cache_tb_directed.MEM_LATENCY=L -P cache_tb_directed.EXHAUSTIVE=E testbench/cache_tb_directed.v rtl/*.v ; vvp")
cm.append("# compile warnings emitted by iverilog -Wall for all Phase 2 testbenches: %s" % (sh("wc -l < build/compile_warnings.txt").strip() + " lines"))
cm.append("")
cm.append("=" * 100); cm.append("SECTION 1: full directed-testbench log, MEM_LATENCY=4, EXHAUSTIVE=1"); cm.append("=" * 100)
cm += text
cm.append(""); cm.append("=" * 100); cm.append("SECTION 2: latency sweep summary (fixed and pseudo-random memory latency)"); cm.append("=" * 100)
cm += open(f"{R}/phase2_latency_sweep.txt").read().splitlines()
cm.append(""); cm.append("=" * 100); cm.append("SECTION 3: independent reference-model regression (tail)"); cm.append("=" * 100)
cm += [l for l in rm.splitlines() if l.startswith("#") or l.startswith("TOTAL") or l.startswith("RESULT")]
cm.append(""); cm.append("=" * 100); cm.append("SECTION 4: mutation check"); cm.append("=" * 100)
cm += open(f"{R}/phase2_mutation_results.txt").read().splitlines()
open(f"{R}/complete_test_results.txt", "w").write("\n".join(cm) + "\n")
print("wrote TEST_RESULTS.md, results/complete_test_results.txt, coverage_summary.md, performance_summary.md")
print("tests: %d (%d pass)  checks ids: %d  fixed-L logs: %d  var-L logs: %d" % (tot_tests, tot_pass, len(checks), n_fix, n_var))
