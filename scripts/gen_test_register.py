#!/usr/bin/env python3
"""Generate the Phase 1 test register (results/phase1_test_register.md) from the saved simulation log. (The consolidated TEST_RESULTS.md is produced by scripts/gen_phase2_reports.py.)
Nothing is typed by hand: every row comes from results/phase1_test_results.txt.
Usage (repo root): python3 -I scripts/gen_test_register.py"""
import re, collections, datetime

LOG = "results/phase1_test_results.txt"
rows = collections.OrderedDict()
pat = re.compile(r"^\[(PASS|FAIL)\] (\S+) (.*?) \| expected=(\S+) actual=(\S+)")
for line in open(LOG):
    m = pat.match(line)
    if not m: continue
    res, tid, desc, exp, act = m.groups()
    r = rows.setdefault(tid, {"desc": desc, "n": 0, "fail": 0, "exp": exp, "act": act})
    r["n"] += 1
    if res == "FAIL": r["fail"] += 1

total = sum(r["n"] for r in rows.values()); fails = sum(r["fail"] for r in rows.values())
out = []
out.append("# TEST_RESULTS.md - Consolidated Test Register\n")
out.append("*Generated by `scripts/gen_test_register.py` from `%s`. Do not edit by hand.*\n" % LOG)
out.append("## Phase 1 - directed tests (`testbench/cache_tb.v`, `MEM_LATENCY=4`)\n")
out.append("Each row is one check ID; IDs inside loops execute several times (column *Runs*). "
           "*Expected/Actual* show the first execution (values in hex).\n")
out.append("| Test ID | Description | Runs | Expected | Actual | Result | Evidence |")
out.append("|---|---|---|---|---|---|---|")
for tid, r in rows.items():
    res = "PASS" if r["fail"] == 0 else "FAIL (%d)" % r["fail"]
    out.append("| %s | %s | %d | %s | %s | %s | `%s` |" % (tid, r["desc"], r["n"], r["exp"], r["act"], res, LOG))
out.append("")
out.append("**Totals:** %d check executions, %d IDs, %d failures.\n" % (total, len(rows), fails))
out.append("## Phase 1 - supplementary evidence\n")
out.append("| Item | Result | Evidence |")
out.append("|---|---|---|")
sweep = open("results/phase1_latency_sweep.txt").read()
for L, p, f in re.findall(r"SUMMARY \(MEM_LATENCY=(\d+)\): PASS=(\d+) FAIL=(\d+)", sweep):
    out.append("| Full testbench at MEM_LATENCY=%s | PASS=%s FAIL=%s | `results/phase1_latency_sweep.txt` |" % (L, p, f))
mut = [l for l in open("results/phase1_mutation_results.txt") if l.strip()]
det = sum(1 for l in mut if "DETECTED" in l)
out.append("| Mutation check (injected RTL bugs detected) | %d of %d detected | `results/phase1_mutation_results.txt` |" % (det, len(mut)))
out.append("| Yosys generic synthesis check (latches / check pass) | see file | `results/phase1_yosys_check.txt` |")
out.append("| Compile with `-g2001 -Wall` | see file | `results/phase1_compile_log.txt` |")
out.append("")
out.append("## Phase 2 / Phase 3\n\nNOT STARTED (awaiting approval gates).\n")
open("results/phase1_test_register.md", "w").write("\n".join(out))   # TEST_RESULTS.md is generated by scripts/gen_phase2_reports.py
print("wrote results/phase1_test_register.md:", len(rows), "IDs,", total, "checks,", fails, "failures")
